#!/usr/bin/env python3
"""
generate_report.py - Research artifact report generator for ARF-RT.

Collects metrics from test artifacts, coverage data, and research logs,
then renders a Markdown summary report to docs/reports/.
"""

import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS_REPORTS = ROOT / "docs" / "reports"
ARTIFACTS_DIR = ROOT / "artifacts"


def _git_info() -> dict:
    """Collect current git metadata."""
    def _run(args: list[str]) -> str:
        try:
            return subprocess.check_output(
                ["git"] + args, cwd=ROOT, text=True,
                stderr=subprocess.DEVNULL
            ).strip()
        except Exception:
            return "unknown"

    return {
        "branch": _run(["rev-parse", "--abbrev-ref", "HEAD"]),
        "commit": _run(["rev-parse", "--short", "HEAD"]),
        "author": _run(["log", "-1", "--pretty=%an"]),
        "date": _run(["log", "-1", "--pretty=%ci"]),
        "subject": _run(["log", "-1", "--pretty=%s"]),
    }


def _count_tests() -> dict:
    """Count test files and approximate test functions."""
    test_files = list((ROOT / "tests").rglob("test_*.py"))
    total_fns = 0
    for tf in test_files:
        content = tf.read_text(encoding="utf-8", errors="ignore")
        total_fns += content.count("def test_")
    return {
        "files": len(test_files),
        "functions": total_fns,
    }


def _count_source_lines() -> dict:
    """Count lines of Python source code."""
    py_files = list((ROOT / "arf_rt").rglob("*.py"))
    total_lines = 0
    for f in py_files:
        total_lines += len(f.read_text(encoding="utf-8", errors="ignore").splitlines())
    return {
        "files": len(py_files),
        "lines": total_lines,
    }


def _doc_stats() -> dict:
    """Count documentation markdown files and total words."""
    md_files = list((ROOT / "docs").rglob("*.md"))
    total_words = 0
    for f in md_files:
        total_words += len(f.read_text(encoding="utf-8", errors="ignore").split())
    return {
        "files": len(md_files),
        "words": total_words,
    }


def _load_benchmark_results() -> dict | None:
    bench_file = ARTIFACTS_DIR / "benchmark_results.json"
    if bench_file.exists():
        try:
            return json.loads(bench_file.read_text())
        except Exception:
            pass
    return None


def render_report(git: dict, tests: dict, source: dict, docs: dict,
                  bench: dict | None) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    bench_section = ""
    if bench:
        rows = []
        for name, s in bench.items():
            if "error" not in s:
                rows.append(
                    f"| `{name}` | {s['median']*1000:.3f} ms "
                    f"| {s['p95']*1000:.3f} ms | {s['p99']*1000:.3f} ms |"
                )
        if rows:
            bench_section = (
                "\n## ⚡ Performance Benchmarks\n\n"
                "| Benchmark | Median | p95 | p99 |\n"
                "|-----------|-------:|----:|----:|\n"
                + "\n".join(rows) + "\n"
            )

    return f"""# ARF-RT Research Artifact Report

> Auto-generated: {now}

## 🔖 Repository Snapshot

| Field | Value |
|-------|-------|
| Branch | `{git['branch']}` |
| Commit | `{git['commit']}` |
| Author | {git['author']} |
| Date | {git['date']} |
| Message | {git['subject']} |

## 📦 Codebase Metrics

| Metric | Value |
|--------|------:|
| Source files | {source['files']} |
| Source lines | {source['lines']:,} |
| Test files | {tests['files']} |
| Test functions | {tests['functions']} |
| Doc files | {docs['files']} |
| Doc words | {docs['words']:,} |
{bench_section}
## 📋 Notes

- Report generated by `scripts/generate_report.py`
- Run `python scripts/run_tests.py --coverage` for detailed coverage data
- Run `python scripts/benchmark.py` and save output to regenerate benchmarks
"""


def main():
    import argparse

    parser = argparse.ArgumentParser(description="Generate ARF-RT research report")
    parser.add_argument(
        "--output", type=Path,
        default=DOCS_REPORTS / f"report_{datetime.now().strftime('%Y%m%d_%H%M%S')}.md",
        help="Output path for the report"
    )
    parser.add_argument("--print", action="store_true", dest="print_report",
                        help="Print report to stdout")
    args = parser.parse_args()

    git = _git_info()
    tests = _count_tests()
    source = _count_source_lines()
    docs = _doc_stats()
    bench = _load_benchmark_results()

    report = render_report(git, tests, source, docs, bench)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(report, encoding="utf-8")
    print(f"Report written to: {args.output}")

    if args.print_report:
        print("\n" + report)


if __name__ == "__main__":
    main()
